// macOS: a launchd LaunchAgent in the gui/<uid> domain, ~/Library/LaunchAgents/local-review.server.plist. The plist
// and the lifecycle follow Hallway's (server/platform/launchd.ts): the modern launchctl verbs (bootstrap, bootout,
// kickstart, print), RunAtLoad so it starts at login, KeepAlive so it's restarted if it exits.
import fs from 'node:fs';
// POSIX paths whatever OS this runs on, so this platform's logic is tested on every OS
import { posix as path } from 'node:path';
import { type InstalledDefinition, type Runner, type ServiceManager, ServiceManagerError, type ServiceSpec, type ServiceStatus, defaultRunner, nodeVersionOf, removeServiceFile, writeIfChanged } from './manager.js';

const xml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const unxml = (s: string) => s.replace(/&quot;/g, '"').replace(/&gt;/g, '>').replace(/&lt;/g, '<').replace(/&amp;/g, '&');

/** The plist. Pure: test/service.test.ts pins it. */
export function renderPlist(spec: ServiceSpec): string {
  const key = (k: string) => `    <key>${k}</key>`;
  const str = (v: string) => `<string>${xml(v)}</string>`;
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    `<!-- Generated by Local Review (${spec.label}). Don't edit it: \`local-review service install\` rewrites it. -->`,
    // `--` can't appear inside an XML comment
    `<!-- Node ${xml(spec.node.version)}: ${xml(spec.node.path).replace(/--/g, '- -')} -->`,
    '<plist version="1.0">',
    '  <dict>',
    `${key('Label')}              ${str(spec.label)}`,
    key('ProgramArguments'),
    '    <array>',
    ...spec.program.map((a) => `      ${str(a)}`),
    '    </array>',
    `${key('RunAtLoad')}          <true/>`,
    `${key('KeepAlive')}          <true/>`,
    `${key('ThrottleInterval')}   <integer>10</integer>`,
    `${key('WorkingDirectory')}   ${str(spec.cwd)}`,
    `${key('StandardOutPath')}    ${str(spec.log)}`,
    `${key('StandardErrorPath')}  ${str(spec.log)}`,
    key('EnvironmentVariables'),
    '    <dict>',
    ...Object.entries(spec.env).map(([k, v]) => `      <key>${xml(k)}</key>${' '.repeat(Math.max(1, 19 - k.length))}${str(v)}`),
    '    </dict>',
    '  </dict>',
    '</plist>',
    '',
  ];
  return lines.join('\n');
}

/** ProgramArguments and EnvironmentVariables, read back from a plist renderPlist wrote. */
export function parsePlist(text: string): InstalledDefinition | null {
  const args = /<key>ProgramArguments<\/key>\s*<array>([\s\S]*?)<\/array>/.exec(text);
  if (!args) return null;
  const program = [...args[1].matchAll(/<string>([^<]*)<\/string>/g)].map((m) => unxml(m[1]));
  const env: Record<string, string> = {};
  const dict = /<key>EnvironmentVariables<\/key>\s*<dict>([\s\S]*?)<\/dict>/.exec(text);
  if (dict) for (const m of dict[1].matchAll(/<key>([^<]*)<\/key>\s*<string>([^<]*)<\/string>/g)) env[unxml(m[1])] = unxml(m[2]);
  const logs = [...text.matchAll(/<key>Standard(?:Out|Error)Path<\/key>\s*<string>([^<]*)<\/string>/g)].map((m) => unxml(m[1]));
  return { program, env, logs: [...new Set(logs)], nodeVersion: nodeVersionOf(text) };
}

/** `launchctl print gui/<uid>/<label>`: the job's top-level `state`, `pid` and `last exit code`. */
export function parseLaunchctlPrint(text: string): { state: string | null; pid: number | null; lastExitCode: number | null } {
  const top = (k: string) => new RegExp(`^\\t${k} = (.+)$`, 'm').exec(text)?.[1].trim() ?? null;
  const pid = top('pid');
  const exit = top('last exit code');
  return {
    state: top('state'),
    pid: pid && /^\d+$/.test(pid) ? Number(pid) : null,
    lastExitCode: exit && /^-?\d+$/.test(exit) ? Number(exit) : null,
  };
}

export interface LaunchdOptions {
  /** ~/Library/LaunchAgents. */
  dir: string;
  label: string;
  uid: number;
  run?: Runner;
  /** For waiting out a bootout, and the bootstrap retry. */
  sleep?: (ms: number) => Promise<void>;
}

const NO_LAUNCHCTL = 'launchctl is not available: Local Review runs as a service with launchd on macOS';

export function launchdManager({ dir, label, uid, run = defaultRunner, sleep = (ms) => new Promise((r) => setTimeout(r, ms)) }: LaunchdOptions): ServiceManager {
  const domain = `gui/${uid}`;
  const target = `${domain}/${label}`;
  const file = path.join(dir, `${label}.plist`);

  const launchctl = async (args: string[], okCodes: number[] = [0]) => {
    const r = await run('launchctl', args);
    if (r.code === 127) throw new ServiceManagerError(NO_LAUNCHCTL);
    if (!okCodes.includes(r.code)) throw new ServiceManagerError(`launchctl ${args.join(' ')} failed (exit ${r.code}): ${(r.stderr || r.stdout).trim()}`);
    return r;
  };

  const status = async (): Promise<ServiceStatus> => {
    const installed = fs.existsSync(file);
    const r = await run('launchctl', ['print', target]);
    if (r.code === 127) throw new ServiceManagerError(NO_LAUNCHCTL);
    if (r.code !== 0) return { installed, loaded: false, running: false, pid: null, lastExitCode: null, state: null, enabled: null };
    const p = parseLaunchctlPrint(r.stdout);
    return { installed, loaded: true, running: p.state === 'running' && p.pid !== null, pid: p.pid, lastExitCode: p.lastExitCode, state: p.state, enabled: null };
  };

  // A bootout returns before launchd has finished taking the job down, and a bootstrap in that window fails with
  // "5: Input/output error" (Paddock's release CI hit it). So a bootout waits until `print` no longer finds the job,
  // and a bootstrap that still gets error 5 is retried once.
  const bootstrap = async () => {
    const r = await run('launchctl', ['bootstrap', domain, file]);
    if (r.code === 0) return;
    if (r.code === 127) throw new ServiceManagerError(NO_LAUNCHCTL);
    if (r.code === 5) {
      await sleep(1000);
      if ((await run('launchctl', ['bootstrap', domain, file])).code === 0) return;
    }
    throw new ServiceManagerError(`launchctl bootstrap ${domain} ${file} failed (exit ${r.code}): ${(r.stderr || r.stdout).trim()}`);
  };

  // exit 3 / 36 / 113: "No such process" / "Operation now in progress" / "Could not find service": not loaded (or on
  // its way out), as wanted. Then up to 10 seconds for it to be gone.
  const bootout = async () => {
    await launchctl(['bootout', target], [0, 3, 36, 113]);
    for (let i = 0; i < 40; i++) {
      const r = await run('launchctl', ['print', target]);
      if (r.code !== 0) return;
      await sleep(250);
    }
  };

  return {
    kind: 'launchd',
    noun: 'LaunchAgent',
    lifetime: 'It starts at login and is restarted if it exits.',
    stopped: 'It starts again at your next login, or with `local-review service start`.',
    file,
    render: renderPlist,
    parse: parsePlist,
    async write(spec) {
      return writeIfChanged(file, renderPlist(spec));
    },
    async start() {
      // a `launchctl disable` (by hand, or a stop) would make bootstrap refuse; undo it first
      await launchctl(['enable', target]);
      const st = await status();
      if (st.running) return;
      if (!st.loaded) return bootstrap(); // bootstrap starts a RunAtLoad job
      await launchctl(['kickstart', target]);
    },
    async stop() {
      // bootout unloads it and leaves the plist: RunAtLoad loads it again at the next login. Never `disable`, which
      // would keep it off for good (that's what uninstall is for)
      await bootout();
    },
    async restart({ reload = false } = {}) {
      const st = await status();
      if (!st.loaded) return this.start();
      if (!reload) {
        await launchctl(['kickstart', '-k', target]);
        return;
      }
      // a changed plist is only read at bootstrap
      await bootout();
      await launchctl(['enable', target]);
      await bootstrap();
    },
    status,
    async remove() {
      await bootout();
      // clear any disabled override, so a later install of the same label just works
      await launchctl(['enable', target]);
      removeServiceFile(file, dir);
    },
  };
}
