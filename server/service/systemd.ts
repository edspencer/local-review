// Linux: a systemd user unit, ~/.config/systemd/user/local-review-server.service (or under $XDG_CONFIG_HOME), the
// equivalent of the macOS LaunchAgent in launchd.ts. As in Hallway's server/platform/systemd.ts:
//   RunAtLoad          → `[Install] WantedBy=default.target`, and `systemctl --user enable`
//   KeepAlive          → `Restart=always`
//   ThrottleInterval   → `RestartSec=10`
//   StandardOut/ErrorPath → `StandardOutput=append:<file>` / `StandardError=append:<file>`, in the data home's logs/
import fs from 'node:fs';
// POSIX paths whatever OS this runs on, so this platform's logic is tested on every OS
import { posix as path } from 'node:path';
import { type InstalledDefinition, type Runner, type ServiceManager, ServiceManagerError, type ServiceSpec, type ServiceStatus, defaultRunner, removeServiceFile, writeIfChanged } from './manager.js';

/** `local-review.server` → `local-review-server.service`. */
export const unitName = (label: string) => `${label.replace(/\./g, '-')}.service`;

/** `%` starts a specifier everywhere in a unit file; `$` an environment variable in ExecStart. */
const pct = (s: string) => s.replace(/%/g, '%%');
const cEscape = (s: string) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\t/g, '\\t');
const cUnescape = (s: string) => s.replace(/\\(.)/g, (_, c) => (c === 'n' ? '\n' : c === 't' ? '\t' : c));

/** One ExecStart word: specifiers and variables escaped, quoted when it has to be. */
export function execWord(a: string): string {
  const s = pct(a).replace(/\$/g, '$$$$');
  return s === '' || /[\s"'\\;]/.test(s) ? `"${cEscape(s)}"` : s;
}

/** The other way, for an ExecStart line execWord wrote: its words. */
export function execWords(line: string): string[] {
  const out: string[] = [];
  for (const m of line.matchAll(/"((?:[^"\\]|\\.)*)"|(\S+)/g)) {
    const w = m[1] !== undefined ? cUnescape(m[1]) : m[2];
    out.push(w.replace(/\$\$/g, '$').replace(/%%/g, '%'));
  }
  return out;
}

/** The unit. Pure: test/service.test.ts pins it. */
export function renderUnit(spec: ServiceSpec): string {
  const lines = [
    `# Generated by Local Review (${spec.label}). Don't edit it: \`local-review service install\` rewrites it.`,
    `# Node ${spec.node.version}: ${spec.node.path}`,
    '[Unit]',
    `Description=${pct(spec.description)}`,
    '',
    '[Service]',
    'Type=simple',
    `WorkingDirectory=${pct(spec.cwd)}`,
    `ExecStart=${spec.program.map(execWord).join(' ')}`,
    ...Object.entries(spec.env).map(([k, v]) => `Environment="${cEscape(pct(`${k}=${v}`))}"`),
    `StandardOutput=append:${pct(spec.stdout)}`,
    `StandardError=append:${pct(spec.stderr)}`,
    'Restart=always',
    'RestartSec=10',
    '',
    '[Install]',
    'WantedBy=default.target',
    '',
  ];
  return lines.join('\n');
}

/** ExecStart and Environment, read back from a unit renderUnit wrote. */
export function parseUnit(text: string): InstalledDefinition | null {
  const exec = /^ExecStart=(.*)$/m.exec(text);
  if (!exec) return null;
  const env: Record<string, string> = {};
  for (const m of text.matchAll(/^Environment="((?:[^"\\]|\\.)*)"$/gm)) {
    const kv = cUnescape(m[1]).replace(/%%/g, '%');
    const i = kv.indexOf('=');
    if (i > 0) env[kv.slice(0, i)] = kv.slice(i + 1);
  }
  return { program: execWords(exec[1]), env };
}

/** `systemctl --user show -p …` output: KEY=VALUE lines. */
export function parseShow(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split('\n')) {
    const i = line.indexOf('=');
    if (i > 0) out[line.slice(0, i)] = line.slice(i + 1).trim();
  }
  return out;
}

export interface SystemdOptions {
  /** ~/.config/systemd/user (or $XDG_CONFIG_HOME/systemd/user). */
  dir: string;
  label: string;
  run?: Runner;
}

const SHOW_PROPS = 'LoadState,ActiveState,SubState,MainPID,ExecMainStatus,ExecMainPID,UnitFileState';

export function systemdManager({ dir, label, run = defaultRunner }: SystemdOptions): ServiceManager {
  const unit = unitName(label);
  const file = path.join(dir, unit);

  const systemctl = async (args: string[], okCodes: number[] = [0]) => {
    const r = await run('systemctl', ['--user', ...args]);
    if (r.code === 127) throw new ServiceManagerError("systemctl is not available: Local Review's service needs systemd's per-user instance (`systemctl --user`)");
    if (/Failed to connect to (user scope )?bus|DBUS_SESSION_BUS_ADDRESS|XDG_RUNTIME_DIR/.test(r.stderr))
      throw new ServiceManagerError(
        `can't reach systemd's per-user instance (${r.stderr.trim()}). Run this from a login session, or check that $XDG_RUNTIME_DIR is set (usually /run/user/$(id -u)).`,
      );
    if (!okCodes.includes(r.code)) throw new ServiceManagerError(`systemctl --user ${args.join(' ')} failed (exit ${r.code}): ${(r.stderr || r.stdout).trim()}`);
    return r;
  };

  const status = async (): Promise<ServiceStatus> => {
    const installed = fs.existsSync(file);
    const r = await systemctl(['show', unit, `--property=${SHOW_PROPS}`], [0, 1, 4]);
    const p = parseShow(r.stdout);
    const loaded = p.LoadState === 'loaded';
    const running = p.ActiveState === 'active' || p.ActiveState === 'reloading';
    const pid = Number(p.MainPID) || null;
    // ExecMainStatus is the exit status of the last run; meaningless while it's the one running now
    const exited = !running && Number(p.ExecMainPID) > 0;
    return {
      installed,
      loaded,
      running,
      pid: running ? pid : null,
      lastExitCode: exited && /^-?\d+$/.test(p.ExecMainStatus ?? '') ? Number(p.ExecMainStatus) : null,
      state: p.ActiveState ? `${p.ActiveState}${p.SubState ? ` (${p.SubState})` : ''}` : null,
      enabled: p.UnitFileState ? p.UnitFileState === 'enabled' || p.UnitFileState === 'enabled-runtime' : null,
    };
  };

  return {
    kind: 'systemd',
    noun: 'systemd user unit',
    lifetime:
      "It starts with your user session and is restarted if it exits. To keep it running while you're logged out, and start it at boot, enable lingering once: `loginctl enable-linger $USER`.",
    file,
    render: renderUnit,
    parse: parseUnit,
    async write(spec) {
      const changed = writeIfChanged(file, renderUnit(spec));
      if (changed) await systemctl(['daemon-reload']);
      return changed;
    },
    async start() {
      await systemctl(['enable', '--quiet', unit]);
      await systemctl(['start', unit]);
    },
    async restart() {
      // `write` already ran daemon-reload for a changed unit, and restart starts an inactive one
      await systemctl(['enable', '--quiet', unit]);
      await systemctl(['restart', unit]);
    },
    status,
    async remove() {
      // 5: not loaded; 1: no such unit. Either is fine here
      await systemctl(['stop', unit], [0, 5]);
      if (fs.existsSync(file)) await systemctl(['disable', '--quiet', unit], [0, 1]);
      removeServiceFile(file, dir);
      await systemctl(['daemon-reload']);
      await systemctl(['reset-failed', unit], [0, 1, 5]);
    },
  };
}
