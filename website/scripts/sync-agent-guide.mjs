// Generates the agent-guide pages from ../AGENT-GUIDE.md.
//
// AGENT-GUIDE.md is the one source of truth: it ships in the npm package and
// `local-review guide` prints it. The docs site shows it too, as one full page
// plus a page for each of three sections that are worth linking to on their
// own. Cloudflare Pages builds with `website/` as the root directory, but the
// whole repo is checked out, so ../AGENT-GUIDE.md is readable; still, the
// pages are generated here and COMMITTED (like sync-brand's copies), so the
// site builds from its own files and a reviewer sees the change in the diff.
//
//   node scripts/sync-agent-guide.mjs           rewrite the pages
//   node scripts/sync-agent-guide.mjs --check   exit 1 if they're stale
//
// The root test suite (test/docs.test.ts) runs the check too, so a change to
// AGENT-GUIDE.md that isn't synced fails CI. Don't edit the generated pages.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
export const GUIDE = join(site, '..', 'AGENT-GUIDE.md');
const SITE_URL = 'https://local-review.edspencer.net';
const GUIDE_PAGE = '/agents/agent-guide/';
// "Edit page" on a generated page edits the source, not the copy.
const EDIT_URL = 'https://github.com/edspencer/local-review/edit/main/AGENT-GUIDE.md';

const banner = (what) =>
	`<!-- Generated by website/scripts/sync-agent-guide.mjs from ${what}. Do not edit: change AGENT-GUIDE.md and re-run it. -->\n`;

/** Pages that are one `## ` section of the guide, each linked from the sidebar on its own. */
const SECTIONS = [
	{
		file: 'agents/plan-command.md',
		heading: 'The plan command',
		title: 'The plan command',
		description: 'Print what each PR should be on GitHub, without changing anything.',
		lede: '`local-review plan` prints what each PR in a stack should be on GitHub: its branch, its base, and its exact title and body. An agent publishes from it, so publishing is mechanical. The full flag list is in the [CLI reference](/reference/cli/).',
	},
	{
		file: 'agents/publishing-stacked-prs.md',
		heading: 'Materializing with GitHub native stacked PRs',
		title: 'Publishing as GitHub stacked PRs',
		description: 'How an agent turns a reviewed stack into GitHub native stacked pull requests.',
		lede: 'When the reviewer says a stack is ready, the agent pushes its branches, opens one PR per commit with the titles and bodies from [the plan](/agents/plan-command/), links them into a GitHub stack and records each PR back in Local Review. Local Review itself never talks to GitHub.',
	},
	{
		file: 'agents/hand-off-prompt.md',
		heading: 'Hand-off prompt template',
		title: 'Hand-off prompt',
		description: 'A prompt to paste into your agent so it addresses your review the right way.',
		lede: 'Finished a round of review? Paste this into a new chat with your coding agent, fill in the `<…>`s, and it will work through your open threads the way the agent guide describes.',
	},
];

const yamlString = (s) => JSON.stringify(s);

/** Doc-site URLs become site-relative, so the build's link check sees them and they work on preview deploys. */
const relink = (md) => md.replaceAll(`${SITE_URL}/`, '/');

/** Split markdown into a preamble and `## ` sections, ignoring headings inside code fences. */
function sections(md) {
	const out = [{ heading: null, lines: [] }];
	let fence = false;
	for (const line of md.split('\n')) {
		if (/^\s*(```|~~~)/.test(line)) fence = !fence;
		const m = !fence && /^## (.+)$/.exec(line);
		if (m) out.push({ heading: m[1].trim(), lines: [] });
		else out.at(-1).lines.push(line);
	}
	return out;
}

/** One heading level up (### → ##), outside code fences: an extracted section's subsections. */
function promote(md) {
	let fence = false;
	return md
		.split('\n')
		.map((line) => {
			if (/^\s*(```|~~~)/.test(line)) fence = !fence;
			return !fence && /^#{3,6} /.test(line) ? line.slice(1) : line;
		})
		.join('\n');
}

/** GitHub-style heading slug (what Starlight's anchors use), for the headings this guide has. */
const slug = (h) => h.toLowerCase().replace(/[^\p{L}\p{N}\s-]/gu, '').replace(/\s/g, '-');

/** @returns {Record<string, string>} page path (under src/content/docs/) → contents */
export function renderPages(guide) {
	const h1 = /^# (.+)\n/.exec(guide);
	if (!h1) throw new Error('AGENT-GUIDE.md: expected a `# ` title on its first line');
	const body = relink(guide.slice(h1[0].length)).replace(/^\n+/, '');
	const pages = {
		'agents/agent-guide.md':
			`---\ntitle: ${yamlString(h1[1])}\ndescription: ${yamlString('How an AI coding agent drives Local Review from the repo it is working on: the data model, review threads, fixups, branches, publishing and merges.')}\neditUrl: ${EDIT_URL}\n---\n\n` +
			banner('AGENT-GUIDE.md') +
			'\n:::tip[The same guide, in your terminal]\n`npx local-review guide` prints this page for an agent to read. It ships in the npm package as `AGENT-GUIDE.md`, so it always matches the version you run.\n:::\n\n' +
			body,
	};
	const all = sections(body);
	for (const s of SECTIONS) {
		const found = all.find((x) => x.heading === s.heading);
		if (!found) throw new Error(`AGENT-GUIDE.md: no "## ${s.heading}" section (website/scripts/sync-agent-guide.mjs SECTIONS)`);
		// Links to other parts of the guide now point at the full page.
		const text = promote(found.lines.join('\n')).replace(/\]\(#/g, `](${GUIDE_PAGE}#`).trim();
		pages[s.file] =
			`---\ntitle: ${yamlString(s.title)}\ndescription: ${yamlString(s.description)}\neditUrl: ${EDIT_URL}\n# The same words are on the full agent guide page; search finds them there.\npagefind: false\n---\n\n` +
			banner(`the "${s.heading}" section of AGENT-GUIDE.md`) +
			`\n${s.lede}\n\n` +
			`:::note[From the agent guide]\nThis page is the [agent guide](${GUIDE_PAGE}#${slug(s.heading)})'s "${s.heading}" section, word for word. Agents read the whole guide with \`npx local-review guide\`.\n:::\n\n` +
			text +
			'\n';
	}
	return pages;
}

function main() {
	const check = process.argv.includes('--check');
	const pages = renderPages(readFileSync(GUIDE, 'utf8'));
	let stale = 0;
	for (const [rel, text] of Object.entries(pages)) {
		const file = join(site, 'src/content/docs', rel);
		let old = null;
		try {
			old = readFileSync(file, 'utf8');
		} catch {}
		if (old === text) continue;
		if (check) {
			console.error(`stale: website/src/content/docs/${rel} (run: cd website && node scripts/sync-agent-guide.mjs)`);
			stale++;
		} else {
			writeFileSync(file, text);
			console.log(`AGENT-GUIDE.md -> website/src/content/docs/${rel}`);
		}
	}
	if (stale) process.exit(1);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
