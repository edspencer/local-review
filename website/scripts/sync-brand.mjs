// Copies the brand kit from ../brand into this site.
//
// Cloudflare Pages builds with `website/` as the root directory, so the site
// cannot reference ../brand at build time: the assets are COPIED in and
// committed. Run this after brand/ changes (`npm run sync-brand`), then commit.
//
// One file is derived rather than copied. The docs header and the landing nav
// are plum, and brand/README.md says that on plum you use the white wordmark
// and give the tile a faint edge, as the social cards do. That edge is the same
// transform brand/generate.mjs applies to the cards.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const brand = join(site, '..', 'brand');

const copies = {
	'favicon.svg': 'public/favicon.svg',
	'favicon.ico': 'public/favicon.ico',
	'apple-touch-icon.png': 'public/apple-touch-icon.png',
	'og-image.png': 'public/og-image.png',
};
for (const [from, to] of Object.entries(copies)) {
	copyFileSync(join(brand, from), join(site, to));
	console.log(`brand/${from} -> website/${to}`);
}

const dark = readFileSync(join(brand, 'lockup-dark.svg'), 'utf8');
const onPlum = dark.replace(
	/(<rect id="tile"[^>]*?)\/>/,
	'$1 stroke="#ffffff" stroke-opacity="0.22" stroke-width="0.5"/>',
);
if (onPlum === dark) throw new Error('lockup-dark.svg: no <rect id="tile"> to edge; has the brand kit changed?');
const banner = '<!-- Generated by website/scripts/sync-brand.mjs from brand/lockup-dark.svg, with a faint tile edge for plum backgrounds. Do not edit. -->\n';
const lockup = 'src/assets/lockup-on-plum.svg';
mkdirSync(dirname(join(site, lockup)), { recursive: true });
writeFileSync(join(site, lockup), banner + onPlum);
console.log(`brand/lockup-dark.svg (+ tile edge) -> website/${lockup}`);
